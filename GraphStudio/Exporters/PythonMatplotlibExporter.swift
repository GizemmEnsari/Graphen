import Foundation

/// Generates a Python script that renders the graph with Matplotlib.
public struct PythonMatplotlibExporter: CodeExporter {
    public var language: CodeLanguage { .pythonMatplotlib }
    public init() {}

    public func export(_ graph: Graph) -> String {
        var lines: [String] = []
        lines.append("import matplotlib.pyplot as plt")
        lines.append("")
        lines.append("# Generated by GraphStudio from \"\(escaped(graph.title))\"")

        switch graph.chartType {
        case .pie:
            let series = graph.series.first
            let labels = CodeNumber.stringArray(series?.points.map { $0.label ?? String($0.x) } ?? [])
            let values = CodeNumber.array(series?.points.map(\.y) ?? [])
            lines.append("labels = \(labels)")
            lines.append("sizes = \(values)")
            lines.append("plt.pie(sizes, labels=labels, autopct='%1.1f%%', startangle=90)")
            lines.append("plt.title(\"\(escaped(graph.title))\")")
        case .bar, .horizontalBar:
            for (i, series) in graph.series.enumerated() {
                lines.append("x\(i) = \(CodeNumber.array(series.points.map(\.x)))")
                lines.append("y\(i) = \(CodeNumber.array(series.points.map(\.y)))")
            }
            lines.append("fig, ax = plt.subplots()")
            for (i, series) in graph.series.enumerated() {
                let offset = 0.1 * Double(i)
                let args = graph.chartType == .horizontalBar
                    ? "ax.barh(x\(i), y\(i), color=\"\(series.color.hex)\", label=\"\(escaped(series.name))\")"
                    : "ax.bar([v + \(offset) for v in x\(i)], y\(i), width=0.2, color=\"\(series.color.hex)\", label=\"\(escaped(series.name))\")"
                lines.append(args)
            }
            lines.append("ax.set_xlabel(\"\(escaped(graph.style.xAxis.label ?? "X Label"))\")")
            lines.append("ax.set_ylabel(\"\(escaped(graph.style.yAxis.label ?? "Y Label"))\")")
            lines.append("ax.set_title(\"\(escaped(graph.title))\")")
            lines.append("ax.legend()" + (graph.style.showLegend ? "" : "  # legend hidden when style disables it"))
            lines.append("plt.show()")
        case .scatter:
            for (i, series) in graph.series.enumerated() {
                lines.append("x\(i) = \(CodeNumber.array(series.points.map(\.x)))")
                lines.append("y\(i) = \(CodeNumber.array(series.points.map(\.y)))")
            }
            lines.append("fig, ax = plt.subplots()")
            for (i, series) in graph.series.enumerated() {
                lines.append("ax.scatter(x\(i), y\(i), color=\"\(series.color.hex)\", label=\"\(escaped(series.name))\")")
            }
            lines.append("ax.set_xlabel(\"\(escaped(graph.style.xAxis.label ?? "X Label"))\")")
            lines.append("ax.set_ylabel(\"\(escaped(graph.style.yAxis.label ?? "Y Label"))\")")
            lines.append("ax.set_title(\"\(escaped(graph.title))\")")
            lines.append("ax.legend()")
            lines.append("plt.show()")
        case .line, .area:
            for (i, series) in graph.series.enumerated() {
                lines.append("x\(i) = \(CodeNumber.array(series.points.map(\.x)))")
                lines.append("y\(i) = \(CodeNumber.array(series.points.map(\.y)))")
            }
            lines.append("fig, ax = plt.subplots()")
            for (i, series) in graph.series.enumerated() {
                if graph.chartType == .area {
                    lines.append("ax.fill_between(x\(i), y\(i), color=\"\(series.color.hex)\", alpha=0.3, label=\"\(escaped(series.name))\")")
                }
                lines.append("ax.plot(x\(i), y\(i), color=\"\(series.color.hex)\", label=\"\(escaped(series.name))\")")
            }
            lines.append("ax.set_xlabel(\"\(escaped(graph.style.xAxis.label ?? "X Label"))\")")
            lines.append("ax.set_ylabel(\"\(escaped(graph.style.yAxis.label ?? "Y Label"))\")")
            lines.append("ax.set_title(\"\(escaped(graph.title))\")")
            lines.append("ax.legend()")
            lines.append("plt.show()")
        }

        return lines.joined(separator: "\n") + "\n"
    }
}