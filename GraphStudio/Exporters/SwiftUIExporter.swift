import Foundation

/// Generates a self-contained SwiftUI + Swift Charts source file for a graph.
public struct SwiftUIExporter: CodeExporter {
    public var language: CodeLanguage { .swiftUI }
    public init() {}

    public func export(_ graph: Graph) -> String {
        let typeName = graph.title.validIdentifier + "Chart"
        var lines: [String] = []

        lines.append("import SwiftUI")
        lines.append("import Charts")
        lines.append("")
        lines.append("// Generated by GraphStudio from \"\(escaped(graph.title))\"")
        lines.append("// Chart type: \(graph.chartType.displayName)")
        lines.append("struct \(typeName): View {")
        lines.append("")
        lines.append("    // MARK: Data")
        for (i, series) in graph.series.enumerated() {
            lines.append("    let series\(i)X = \(CodeNumber.array(series.points.map(\.x)))")
            lines.append("    let series\(i)Y = \(CodeNumber.array(series.points.map(\.y)))")
        }
        lines.append("")
        lines.append("    var body: some View {")
        lines.append("        Chart {")

        switch graph.chartType {
        case .line, .area, .scatter, .bar, .horizontalBar:
            for (i, series) in graph.series.enumerated() {
                lines += marks(for: graph.chartType, index: i, color: series.color, name: series.name)
            }
        case .pie:
            lines.append("            // Pie charts need a custom SwiftUI view; the slice")
            lines.append("            // values are in the arrays above (use `sectorMark`/custom arcs).")
        }

        lines.append("        }")
        lines.append("        .chartXAxisLabel(\"\(escaped(graph.style.xAxis.label ?? "X Label"))\")")
        lines.append("        .chartYAxisLabel(\"\(escaped(graph.style.yAxis.label ?? "Y Label"))\")")
        lines.append("        .frame(height: 400)")
        lines.append("        .padding()")
        lines.append("    }")
        lines.append("}")
        lines.append("")
        lines.append("enum ChartKind { case bar, line, scatter, area, pie, horizontalBar }")

        return lines.joined(separator: "\n") + "\n"
    }

    private func marks(for type: ChartType, index i: Int, color: ColorValue, name: String) -> [String] {
        let colorLiteral = color.swiftUIColorLiteral
        switch type {
        case .line:
            return [
                "            ForEach(0..<series\(i)X.count, id: \\.self) { i in",
                "                LineMark(x: .value(\"x\", series\(i)X[i]), y: .value(\"y\", series\(i)Y[i]))",
                "                    .foregroundStyle(\(colorLiteral))",
                "                    .interpolationMethod(.catmullRom)",
                "                    .annotation(position: .top) { Text(\"\(escaped(name))\") }",
                "            }",
            ]
        case .area:
            return [
                "            ForEach(0..<series\(i)X.count, id: \\.self) { i in",
                "                AreaMark(x: .value(\"x\", series\(i)X[i]), y: .value(\"y\", series\(i)Y[i]))",
                "                    .foregroundStyle(\(colorLiteral).opacity(0.4))",
                "                    .interpolationMethod(.monotone)",
                "            }",
            ]
        case .scatter:
            return [
                "            ForEach(0..<series\(i)X.count, id: \\.self) { i in",
                "                PointMark(x: .value(\"x\", series\(i)X[i]), y: .value(\"y\", series\(i)Y[i]))",
                "                    .foregroundStyle(\(colorLiteral))",
                "            }",
            ]
        case .bar:
            return [
                "            ForEach(0..<series\(i)X.count, id: \\.self) { i in",
                "                BarMark(x: .value(\"x\", series\(i)X[i]), y: .value(\"y\", series\(i)Y[i]))",
                "                    .foregroundStyle(\(colorLiteral))",
                "            }",
            ]
        case .horizontalBar:
            return [
                "            ForEach(0..<series\(i)X.count, id: \\.self) { i in",
                "                BarMark(x: .value(\"y\", series\(i)Y[i]), y: .value(\"x\", series\(i)X[i]))",
                "                    .foregroundStyle(\(colorLiteral))",
                "            }",
            ]
        case .pie:
            return []
        }
    }
}